"""Build spec/INDEX.md: every rule ID and section heading with its file and line.

Usage: python3 scripts/build_index.py [--check]
With --check, exit with status 1 if spec/INDEX.md is out of date.
"""
import pathlib
import re
import sys

SPEC = pathlib.Path(__file__).resolve().parent.parent / "spec"
INDEX = SPEC / "INDEX.md"
HEADING = re.compile(r"^(#{1,3}) (.+)$")
RULE = re.compile(r"\*\*([A-Z][A-Z0-9]*-[0-9][0-9.]*)\*\*|^\| ([A-Z][A-Z0-9]*-[0-9][0-9.]*|[A-Z]{1,2}[0-9]+) \|")


def collect():
    rows = []
    for path in sorted(SPEC.rglob("*.md")):
        if path == INDEX:
            continue
        relative = path.relative_to(SPEC).as_posix()
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            heading = HEADING.match(line)
            if heading:
                rows.append((relative, number, "section", heading.group(2).strip()))
                continue
            for match in RULE.finditer(line):
                rule_id = match.group(1) or match.group(2)
                if rule_id.startswith("F") and rule_id[1:].isdigit():
                    continue
                rows.append((relative, number, "rule", rule_id))
    return rows


def render(rows):
    lines = [
        "# Index",
        "",
        "Generated by `scripts/build_index.py`. Do not edit by hand.",
        "",
        "Find a rule ID or a section here, then open only that file at that line.",
        "",
        "| File | Line | Kind | Entry |",
        "|---|---|---|---|",
    ]
    for relative, number, kind, entry in rows:
        lines.append(f"| [{relative}]({relative}#L{number}) | {number} | {kind} | {entry} |")
    return "\n".join(lines) + "\n"


def main():
    content = render(collect())
    if "--check" in sys.argv:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else ""
        if current != content:
            print("spec/INDEX.md is out of date: run python3 scripts/build_index.py")
            sys.exit(1)
        return
    INDEX.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
