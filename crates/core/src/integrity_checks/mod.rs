/// Generates the integrity checks of the model of `handle` in `dialect` (E0H-4, CHK-2).
///
/// The document lists the checks E0 recorded, sorted by `check_id` (E0H-4.3): the
/// `key_uniqueness` and `orphan_keys` checks of every usable relationship, the `summary` check
/// of every summary, the `population` check of every population and the `semi_additive` check
/// of every semi-additive metric. Each check's query is generated by the same generator as
/// `compile` (CHK-4.2); it returns one row per violation (CHK-2.1, CHK-2.5) and applies no row
/// policy (CHK-2.2). A `summary` check carries the summary's build query, generated from the
/// same base plan (CHK-5.1, CHK-5.4). A query that reads the day of a `timestamp with time
/// zone` has one `time_zone` slot (CHK-7.3). The `semi_additive` check of a metric whose
/// `over` or `entity` is a field of a dataset reached from its home dataset is left out.
///
/// # Errors
///
/// The compile error document (PLN-5), with the handle's warnings: `E6-01` when the
/// `clickhouse` dialect cannot express a value a check reads (E6-7.11, E6-7.12), `E_INTERNAL`,
/// without location, for a defect of the compiler (PLN-5.1a).
///
/// # Example
///
/// ```
/// use menura_core::{Dialect, LoadOptions, integrity_checks, load};
/// # let model = include_bytes!("../../tests/fixtures/shop/model.yaml");
/// # let catalog_schema = include_bytes!("../../tests/fixtures/shop/catalog-schema.json");
///
/// let handle = load(model, catalog_schema, None, &LoadOptions::default()).unwrap();
/// let document = integrity_checks(&handle, Dialect::Duckdb).unwrap();
/// assert_eq!(document.model_hash, *handle.model().hash());
/// ```
pub fn integrity_checks(
    handle: &Handle,
    dialect: Dialect,
) -> Result<IntegrityChecksDocument, CompileErrorDocument> {
    generated_checks(handle, dialect).map_err(|error| CompileErrorDocument {
        contract: CompileErrorContract::CompileError,
        contract_version: ContractKind::CompileError.latest_version(),
        errors: vec![error.into_diagnostic()],
        warnings: handle.warnings().cloned().collect(),
    })
}

fn generated_checks(handle: &Handle, dialect: Dialect) -> Result<IntegrityChecksDocument, Stop> {
    let checks = handle
        .model()
        .parts()
        .checks
        .iter()
        .filter_map(|recorded| generated_check(handle, dialect, recorded).transpose())
        .collect::<Result<Vec<_>, _>>()?;
    Ok(IntegrityChecksDocument {
        contract: IntegrityChecksContract::IntegrityChecks,
        contract_version: ContractKind::IntegrityChecks.latest_version(),
        model_hash: handle.model().hash().clone(),
        dialect,
        checks,
    })
}

/// The check `recorded` with its query in `dialect`; `None` for a `semi_additive` check that
/// is left out because its metric reads `over` or `entity` from a reached dataset.
fn generated_check(
    handle: &Handle,
    dialect: Dialect,
    recorded: &RecordedCheck,
) -> Result<Option<IntegrityCheck>, Stop> {
    let model = handle.model();
    let catalog = handle.catalog_schema();
    match recorded.kind {
        CheckKind::Summary => summary_check(handle, dialect, recorded).map(Some),
        CheckKind::KeyUniqueness | CheckKind::OrphanKeys => {
            relationship_check(handle, dialect, recorded).map(Some)
        }
        CheckKind::Population => {
            let target = NormalizedName::new(&recorded.target);
            let (generated, dataset) = population_check_sql(dialect, model, catalog, &target)?;
            let check = row_check(
                handle,
                recorded,
                ContractCheckKind::Population,
                generated,
                &[&dataset],
            )?;
            Ok(Some(check))
        }
        CheckKind::SemiAdditive => {
            let Some((generated, datasets)) =
                semi_additive_check_sql(dialect, model, catalog, &recorded.target)?
            else {
                return Ok(None);
            };
            let read: Vec<&NormalizedName> = datasets.iter().collect();
            row_check(
                handle,
                recorded,
                ContractCheckKind::SemiAdditive,
                generated,
                &read,
            )
            .map(Some)
        }
    }
}

/// The `population` or `semi_additive` check `recorded` of `kind`, with its generated query
/// and the datasets it reads.
fn row_check(
    handle: &Handle,
    recorded: &RecordedCheck,
    kind: ContractCheckKind,
    generated: CheckSql,
    read: &[&NormalizedName],
) -> Result<IntegrityCheck, Stop> {
    Ok(IntegrityCheck {
        check_id: recorded.check_id.clone(),
        kind,
        target: recorded.target.clone(),
        definition_hash: recorded.definition_hash.clone(),
        sql: generated.sql,
        parameters: generated.parameters,
        sources: sources(handle, &recorded.check_id, read)?,
        build: None,
    })
}

/// The `summary` check `recorded` with its query and its build query in `dialect` (CHK-6.6,
/// CHK-5.4). Both read the base and bind the same slots (CHK-7.2).
fn summary_check(
    handle: &Handle,
    dialect: Dialect,
    recorded: &RecordedCheck,
) -> Result<IntegrityCheck, Stop> {
    let model = handle.model();
    let summary = model
        .parts()
        .summaries
        .iter()
        .find(|summary| summary.dataset.as_str() == recorded.target)
        .ok_or_else(|| {
            InternalError::new(
                STAGE,
                format!("the check {} names no summary", recorded.check_id),
            )
        })?;
    let parts = SummaryParts::of(summary, model)?;
    let (sql, parameters) = generated_sql(handle, dialect, &summary_check_plan(&parts)?)?;
    let (build, columns) = build_plan(&parts, handle.catalog_schema())?;
    let (build_sql, build_parameters) = generated_sql(handle, dialect, &build)?;
    let mut sources = vec![parts.base.source.clone(), parts.dataset.source.clone()];
    sources.sort();
    sources.dedup();
    Ok(IntegrityCheck {
        check_id: recorded.check_id.clone(),
        kind: ContractCheckKind::Summary,
        target: recorded.target.clone(),
        definition_hash: recorded.definition_hash.clone(),
        sql,
        parameters,
        sources,
        build: Some(BuildQuery {
            sql: build_sql,
            parameters: build_parameters,
            columns,
        }),
    })
}

/// The relationship check `recorded` with its query in `dialect`.
fn relationship_check(
    handle: &Handle,
    dialect: Dialect,
    recorded: &RecordedCheck,
) -> Result<IntegrityCheck, Stop> {
    let model = handle.model();
    let catalog = handle.catalog_schema();
    let relationship = model
        .relationship(&NormalizedName::new(&recorded.target))
        .ok_or_else(|| {
            InternalError::new(
                STAGE,
                format!("the check {} names no relationship", recorded.check_id),
            )
        })?;
    let (kind, plan, read) = match recorded.kind {
        CheckKind::KeyUniqueness => (
            ContractCheckKind::KeyUniqueness,
            key_uniqueness_plan(relationship, model, catalog)?,
            vec![&relationship.to],
        ),
        CheckKind::OrphanKeys => (
            ContractCheckKind::OrphanKeys,
            orphan_keys_plan(relationship, model, catalog)?,
            vec![&relationship.from, &relationship.to],
        ),
        other => {
            return Err(InternalError::new(
                STAGE,
                format!("checks of kind {} are not generated yet", other.as_str()),
            )
            .into());
        }
    };
    let (sql, parameters) = generated_sql(handle, dialect, &plan)?;
    Ok(IntegrityCheck {
        check_id: recorded.check_id.clone(),
        kind,
        target: recorded.target.clone(),
        definition_hash: recorded.definition_hash.clone(),
        sql,
        parameters,
        sources: sources(handle, &recorded.check_id, &read)?,
        build: None,
    })
}

/// The SQL of `plan` in `dialect` and its parameters: values the compiler fixed and slots the
/// pipeline binds (CHK-7.1).
fn generated_sql(
    handle: &Handle,
    dialect: Dialect,
    plan: &PlanNode,
) -> Result<(String, Vec<CheckParameter>), Stop> {
    let sources = Sources {
        catalog: handle.catalog_schema(),
        model: handle.model(),
    };
    let generated = check_sql(dialect, &CheckShape::Plan(plan), sources)?;
    Ok((generated.sql, generated.parameters))
}

/// The `source` of each dataset of `read`, each once, sorted in CON-5 order (CHK-2.4).
fn sources(
    handle: &Handle,
    check_id: &str,
    read: &[&NormalizedName],
) -> Result<Vec<String>, InternalError> {
    let mut sources = read
        .iter()
        .map(|name| {
            handle
                .model()
                .dataset(name)
                .map(|dataset| dataset.source.clone())
                .ok_or_else(|| {
                    InternalError::new(
                        STAGE,
                        format!(
                            "the check {check_id} reads the unknown dataset {}",
                            name.as_str()
                        ),
                    )
                })
        })
        .collect::<Result<Vec<_>, _>>()?;
    sources.sort();
    sources.dedup();
    Ok(sources)
}
