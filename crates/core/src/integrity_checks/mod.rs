/// Generates the integrity checks of the model of `handle` in `dialect` (E0H-4, CHK-2).
///
/// The document lists the `key_uniqueness`, `orphan_keys`, `population` and `semi_additive`
/// checks E0 recorded, sorted by `check_id` (E0H-4.3). Each check's query is generated by the
/// same generator as `compile` (CHK-4.2); it returns one row per violation (CHK-2.1, CHK-2.5)
/// and applies no row policy (CHK-2.2). A query that reads the day of a `timestamp with time
/// zone` has one `time_zone` slot (CHK-7.3). The `summary` checks are not generated yet, and
/// the `semi_additive` check of a metric whose `over` or `entity` is a field of a dataset
/// reached from its home dataset is left out.
///
/// # Errors
///
/// The compile error document (PLN-5) with `E_INTERNAL`, without location, for a defect of the
/// compiler (PLN-5.1a), with the handle's warnings.
///
/// # Example
///
/// ```
/// use menura_core::{Dialect, LoadOptions, integrity_checks, load};
/// # let model = include_bytes!("../../tests/fixtures/shop/model.yaml");
/// # let catalog_schema = include_bytes!("../../tests/fixtures/shop/catalog-schema.json");
///
/// let handle = load(model, catalog_schema, None, &LoadOptions::default()).unwrap();
/// let document = integrity_checks(&handle, Dialect::Duckdb).unwrap();
/// assert_eq!(document.model_hash, *handle.model().hash());
/// ```
pub fn integrity_checks(
    handle: &Handle,
    dialect: Dialect,
) -> Result<IntegrityChecksDocument, CompileErrorDocument> {
    generated_checks(handle, dialect).map_err(|error| CompileErrorDocument {
        contract: CompileErrorContract::CompileError,
        contract_version: ContractKind::CompileError.latest_version(),
        errors: vec![Stop::from(error).into_diagnostic()],
        warnings: handle.warnings().cloned().collect(),
    })
}

fn generated_checks(
    handle: &Handle,
    dialect: Dialect,
) -> Result<IntegrityChecksDocument, InternalError> {
    let checks = handle
        .model()
        .parts()
        .checks
        .iter()
        .filter(|recorded| generated_kind(recorded.kind))
        .filter_map(|recorded| generated_check(handle, dialect, recorded).transpose())
        .collect::<Result<Vec<_>, _>>()?;
    Ok(IntegrityChecksDocument {
        contract: IntegrityChecksContract::IntegrityChecks,
        contract_version: ContractKind::IntegrityChecks.latest_version(),
        model_hash: handle.model().hash().clone(),
        dialect,
        checks,
    })
}

/// Whether checks of `kind` are generated in this version.
fn generated_kind(kind: CheckKind) -> bool {
    !matches!(kind, CheckKind::Summary)
}

/// The check `recorded` with its query in `dialect`; `None` for a `semi_additive` check that
/// is left out because its metric reads `over` or `entity` from a reached dataset.
fn generated_check(
    handle: &Handle,
    dialect: Dialect,
    recorded: &RecordedCheck,
) -> Result<Option<IntegrityCheck>, InternalError> {
    let Dialect::Duckdb = dialect;
    let model = handle.model();
    let catalog = handle.catalog_schema();
    let (kind, generated, read) = match recorded.kind {
        CheckKind::KeyUniqueness | CheckKind::OrphanKeys => {
            relationship_check_sql(handle, recorded)?
        }
        CheckKind::Population => {
            let (generated, dataset) =
                population_check_sql(model, catalog, &NormalizedName::new(&recorded.target))?;
            (ContractCheckKind::Population, generated, vec![dataset])
        }
        CheckKind::SemiAdditive => {
            let Some((generated, datasets)) =
                semi_additive_check_sql(model, catalog, &recorded.target)?
            else {
                return Ok(None);
            };
            (ContractCheckKind::SemiAdditive, generated, datasets)
        }
        CheckKind::Summary => {
            return Err(InternalError::new(
                STAGE,
                "checks of kind summary are not generated yet",
            ));
        }
    };
    Ok(Some(IntegrityCheck {
        check_id: recorded.check_id.clone(),
        kind,
        target: recorded.target.clone(),
        definition_hash: recorded.definition_hash.clone(),
        sql: generated.sql,
        parameters: generated.parameters.into_iter().map(parameter).collect(),
        sources: sources(handle, &recorded.check_id, &read)?,
        build: None,
    }))
}

/// The `key_uniqueness` or `orphan_keys` check `recorded`: its kind, its SQL and the datasets
/// it reads.
fn relationship_check_sql(
    handle: &Handle,
    recorded: &RecordedCheck,
) -> Result<(ContractCheckKind, GeneratedCheckSql, Vec<NormalizedName>), InternalError> {
    let model = handle.model();
    let catalog = handle.catalog_schema();
    let relationship = model
        .relationship(&NormalizedName::new(&recorded.target))
        .ok_or_else(|| {
            InternalError::new(
                STAGE,
                format!("the check {} names no relationship", recorded.check_id),
            )
        })?;
    let (kind, plan, read) = if recorded.kind == CheckKind::KeyUniqueness {
        (
            ContractCheckKind::KeyUniqueness,
            key_uniqueness_plan(relationship, model, catalog)?,
            vec![relationship.to.clone()],
        )
    } else {
        (
            ContractCheckKind::OrphanKeys,
            orphan_keys_plan(relationship, model, catalog)?,
            vec![relationship.from.clone(), relationship.to.clone()],
        )
    };
    let generated = generate_check_sql(&plan, catalog, model)
        .map_err(|error| InternalError::new("E6", format!("{error:?}")))?;
    Ok((kind, generated, read))
}

/// The contract form of a generated parameter: a fixed value, or the `time_zone` slot
/// (CHK-7.1, CHK-7.3).
fn parameter(generated: GeneratedCheckParameter) -> CheckParameter {
    match generated {
        GeneratedCheckParameter::Fixed(fixed) => CheckParameter::Fixed(fixed),
        GeneratedCheckParameter::TimeZone { position } => CheckParameter::Bound(BoundParameter {
            position,
            logical_type: TextLogicalType,
            binding: Binding::TimeZone,
        }),
    }
}

/// The `source` of each dataset of `read`, each once, sorted in CON-5 order (CHK-2.4).
fn sources(
    handle: &Handle,
    check_id: &str,
    read: &[NormalizedName],
) -> Result<Vec<String>, InternalError> {
    let mut sources = read
        .iter()
        .map(|name| {
            handle
                .model()
                .dataset(name)
                .map(|dataset| dataset.source.clone())
                .ok_or_else(|| {
                    InternalError::new(
                        STAGE,
                        format!(
                            "the check {check_id} reads the unknown dataset {}",
                            name.as_str()
                        ),
                    )
                })
        })
        .collect::<Result<Vec<_>, _>>()?;
    sources.sort();
    sources.dedup();
    Ok(sources)
}
